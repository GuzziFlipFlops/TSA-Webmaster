export const US_STATE_OPTIONS = US_STATES.map((state) => ({ value: state.code, label: state.name }));

export function getStateByCode(code) {
  return US_STATES.find((state) => state.code === code) ?? null;
}

export function findStateByNameOrCode(input) {
  const normalized = String(input ?? "").trim().toLowerCase();
  if (!normalized) return null;
  return US_STATES.find((state) => state.code.toLowerCase() === normalized || state.name.toLowerCase() === normalized) ?? null;
}

export function stateFromZip(zipInput) {
  const match = String(zipInput ?? "").match(/\b(\d{5})\b/);
  if (!match) return null;
  const prefix = Number(match[1].slice(0, 3));
  return US_STATES.find((state) => state.zipPrefixRanges.some(([start, end]) => prefix >= start && prefix <= end)) ?? null;
}

export function stateFromLocationText(input) {
  const normalized = String(input ?? "").trim().toLowerCase().replace(/,\s*/g, " ").replace(/\s+/g, " ");
  if (!normalized) return null;
  const zipState = stateFromZip(normalized);
  if (zipState) return zipState;
  return US_STATES.find((state) => normalized === state.code.toLowerCase() || normalized === state.name.toLowerCase() || normalized.endsWith(` ${state.code.toLowerCase()}`) || normalized.includes(state.name.toLowerCase())) ?? null;
}
